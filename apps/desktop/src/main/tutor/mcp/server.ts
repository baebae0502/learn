import { LearnError, TUTOR_TOOLS, tutorEnvelope, type TutorTool } from '@learn/domain';
import { z } from 'zod';
import { tutorLog } from '../log';
import type { AcpScope } from '../scope';
import { TOOL_ANNOTATIONS, TOOL_DESCRIPTIONS, isTutorTool, toolInputSchemas, type ToolCallResult } from '../tools';

/** Newest first: an unknown version asked for gets the first. */
export const MCP_VERSIONS = ['2025-11-25', '2025-06-18', '2025-03-26', '2024-11-05'] as const;
export type McpVersion = (typeof MCP_VERSIONS)[number];
/** What one MCP session negotiated; null until its initialize. */
export interface McpConnection { version: McpVersion | null }

/** The versions whose tool result may carry structuredContent. */
const STRUCTURED: ReadonlySet<McpVersion> = new Set<McpVersion>(['2025-11-25', '2025-06-18']);

const isVersion = (v: string): v is McpVersion => (MCP_VERSIONS as readonly string[]).includes(v);

/*
 * What comes in is read loosely, like ACP (spec 4.1): the fields Learn reads are checked, and any other field — _meta
 * among them — is dropped, not refused. What goes out is built strict.
 */
const rpcId = z.union([z.number(), z.string().max(256)]);
const message = z.object({
  jsonrpc: z.literal('2.0'),
  // null only in a client's error answer to a message it could not read.
  id: z.union([rpcId, z.null()]).optional(),
  method: z.string().min(1).max(256).optional(),
  params: z.unknown().optional(),
  result: z.unknown().optional(),
  error: z.unknown().optional(),
});
const initializeParams = z.object({ protocolVersion: z.string().max(64) });
const callParams = z.object({ name: z.string().max(256), arguments: z.unknown().optional() });

export type RpcId = z.infer<typeof rpcId>;
export type McpMessage =
  | { kind: 'request'; id: RpcId; method: string; params: unknown }
  | { kind: 'notification'; method: string }
  | { kind: 'response' };

/** One JSON-RPC message as Learn reads it; null when it is none (a batch, a request with a null id, a bare object). */
export function readMcpMessage(raw: unknown): McpMessage | null {
  const parsed = message.safeParse(raw);
  if (!parsed.success) return null;
  const m = parsed.data;
  if (m.method !== undefined) {
    if (m.id === null) return null;
    return m.id === undefined ? { kind: 'notification', method: m.method } : { kind: 'request', id: m.id, method: m.method, params: m.params };
  }
  return m.id !== undefined && (m.result !== undefined || m.error !== undefined) ? { kind: 'response' } : null;
}

const toolDefinition = z.object({
  name: z.enum(TUTOR_TOOLS),
  description: z.string().min(1),
  // Generated by zod; what is checked here is that every input schema stays closed.
  inputSchema: z.object({ type: z.literal('object'), additionalProperties: z.literal(false) }).catchall(z.unknown()),
  annotations: z.object({
    readOnlyHint: z.literal(true), destructiveHint: z.literal(false), idempotentHint: z.literal(true), openWorldHint: z.literal(false),
  }).strict(),
}).strict();

const out = {
  initialize: z.object({
    protocolVersion: z.enum(MCP_VERSIONS),
    capabilities: z.object({ tools: z.object({}).strict() }).strict(),
    serverInfo: z.object({ name: z.literal('learn'), version: z.string().min(1).max(64) }).strict(),
  }).strict(),
  toolsList: z.object({ tools: z.array(toolDefinition).length(TUTOR_TOOLS.length) }).strict(),
  toolsCall: z.object({
    content: z.tuple([z.object({ type: z.literal('text'), text: z.string() }).strict()]),
    isError: z.boolean(),
    structuredContent: tutorEnvelope.optional(),
  }).strict(),
  empty: z.object({}).strict(),
  reply: z.object({ jsonrpc: z.literal('2.0'), id: rpcId, result: z.record(z.string(), z.unknown()) }).strict(),
  error: z.object({
    jsonrpc: z.literal('2.0'), id: rpcId.nullable(), error: z.object({ code: z.number().int(), message: z.string().min(1) }).strict(),
  }).strict(),
};

/** A JSON-RPC error answer, strict; `id` null when the message it answers could not be read. */
export function rpcError(id: RpcId | null, code: number, text: string): Record<string, unknown> {
  return out.error.parse({ jsonrpc: '2.0', id, error: { code, message: text } });
}

/** The three tools as tools/list tells them: their strict zod shapes as JSON Schema, and the read-only hints. */
export function toolDefinitions(): Array<{ name: TutorTool; description: string; inputSchema: Record<string, unknown>; annotations: typeof TOOL_ANNOTATIONS }> {
  return TUTOR_TOOLS.map((name) => {
    const inputSchema: Record<string, unknown> = { ...z.toJSONSchema(toolInputSchemas[name], { io: 'input' }) };
    // MCP's default dialect is the one zod writes; naming it would only confuse a client of an older version.
    delete inputSchema.$schema;
    return { name, description: TOOL_DESCRIPTIONS[name], inputSchema, annotations: TOOL_ANNOTATIONS };
  });
}

export function createMcpServer(d: {
  call(scope: AcpScope, name: TutorTool, args: unknown): Promise<ToolCallResult>;
  /** What serverInfo says; the agent only shows it. */
  version?: string;
}): { handle(scope: AcpScope, conn: McpConnection, message: unknown): Promise<Record<string, unknown> | null> } {
  const serverInfo = { name: 'learn', version: d.version ?? '0.0.0' };
  const reply = (id: RpcId, result: Record<string, unknown>) => out.reply.parse({ jsonrpc: '2.0', id, result });

  async function answer(scope: AcpScope, conn: McpConnection, id: RpcId, method: string, params: unknown): Promise<Record<string, unknown>> {
    // The tools open only to a client that initialized: whoever read the token off the agent's command line gets no
    // further than initialize, which the transport binds to one MCP session.
    if ((method === 'tools/list' || method === 'tools/call') && conn.version === null) return rpcError(id, -32600, 'Server not initialized');
    switch (method) {
      case 'initialize': {
        const p = initializeParams.safeParse(params);
        if (!p.success) return rpcError(id, -32602, 'Invalid params');
        const version = isVersion(p.data.protocolVersion) ? p.data.protocolVersion : MCP_VERSIONS[0];
        const result = out.initialize.parse({ protocolVersion: version, capabilities: { tools: {} }, serverInfo });
        conn.version = version;
        return reply(id, result);
      }
      case 'ping':
        return reply(id, out.empty.parse({}));
      case 'tools/list':
        return reply(id, out.toolsList.parse({ tools: toolDefinitions() }));
      case 'tools/call': {
        const p = callParams.safeParse(params);
        if (!p.success) return rpcError(id, -32602, 'Invalid params');
        // Not a Learn tool: nothing is run or recorded, the tool_reads rows being Learn's tool calls only.
        if (!isTutorTool(p.data.name)) return rpcError(id, -32602, 'Unknown tool');
        const r = await d.call(scope, p.data.name, p.data.arguments);
        const structured = conn.version !== null && STRUCTURED.has(conn.version) && r.envelope !== null;
        return reply(id, out.toolsCall.parse({
          content: [{ type: 'text', text: r.text }], isError: r.isError, ...(structured ? { structuredContent: r.envelope } : {}),
        }));
      }
      default:
        // server/discover among them: Claude asks it first and goes on to initialize when it is not found.
        return rpcError(id, -32601, 'Method not found');
    }
  }

  return {
    async handle(scope, conn, raw) {
      const m = readMcpMessage(raw);
      if (m === null) return rpcError(null, -32600, 'Invalid Request');
      // A notification (notifications/cancelled comes with every stop) or the client's own answer: nothing to say.
      if (m.kind !== 'request') return null;
      try {
        return await answer(scope, conn, m.id, m.method, m.params);
      } catch (e) {
        // The error's message may hold the material's text, so only its code is logged.
        tutorLog('mcp-call-failed', { code: e instanceof LearnError ? e.code : 'INTERNAL' });
        return rpcError(m.id, -32603, 'Internal error');
      }
    },
  };
}
