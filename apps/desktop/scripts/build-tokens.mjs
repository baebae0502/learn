#!/usr/bin/env node
// Generates design/tokens.css and design/tokens.generated.ts from design/tokens.ts.
//   node --experimental-strip-types apps/desktop/scripts/build-tokens.mjs          write
//   node --experimental-strip-types apps/desktop/scripts/build-tokens.mjs --check  exit 1 if stale
// (`pnpm tokens` / `pnpm tokens:check`.) Node ≥ 22.18 strips types without the flag.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const designDir = path.resolve(here, '../src/renderer/src/design');
const tokens = await import(pathToFileURL(path.join(designDir, 'tokens.ts')).href);
const color = await import(pathToFileURL(path.join(designDir, 'color.ts')).href);

const HEADER = 'Generated by apps/desktop/scripts/build-tokens.mjs from tokens.ts — do not edit; run `pnpm tokens`.';

const kebab = (key) => key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const px = (n) => (n === 0 ? '0' : `${n}px`);
const pair = (p) => `light-dark(${p.light}, ${p.dark})`;

function shadow(layers) {
  return layers
    .map((l) => `${l.inset ? 'inset ' : ''}${px(l.x)} ${px(l.y)} ${px(l.blur)} ${px(l.spread)} ${pair(l.color)}`)
    .join(', ');
}

function assertInGamut(name, value) {
  if (color.parseColor(value).clamped) throw new Error(`${name}: ${value} is outside sRGB; lower its chroma`);
}

export function renderCss() {
  const lines = [];
  const decl = (name, value) => lines.push(`    --${name}: ${value};`);
  const section = (title) => lines.push(`    /* ${title} */`);

  section('Colour — themed with light-dark(); the active color-scheme picks the side');
  for (const [key, p] of Object.entries(tokens.colors)) {
    assertInGamut(`${key}.light`, p.light);
    assertInGamut(`${key}.dark`, p.dark);
    decl(kebab(key), pair(p));
  }
  section('Tag and annotation colours (positions 1–8, same in both themes)');
  for (const t of tokens.tagColors) decl(`tag-${t.position}`, t.hex);
  section('Reader page themes');
  for (const [theme, values] of Object.entries(tokens.pageThemes)) {
    for (const [k, v] of Object.entries(values)) decl(`page-${theme}-${kebab(k)}`, v);
    decl(`page-${theme}-highlight-alpha`, String(tokens.highlightAlpha[theme]));
  }
  section('Elevation');
  for (const [key, layers] of Object.entries(tokens.shadows)) decl(`shadow-${key}`, shadow(layers));

  section('Typography');
  decl('font-system', tokens.fonts.system);
  decl('font-pretendard', tokens.fonts.pretendard);
  decl('font-mono', tokens.fonts.mono);
  decl('font-ui', 'var(--font-system)');
  for (const [role, t] of Object.entries(tokens.typeScale)) {
    const name = kebab(role);
    decl(`text-${name}-size`, px(t.size));
    decl(`text-${name}-line`, px(t.line));
    decl(`text-${name}-weight`, String(t.weight));
    decl(`type-${name}`, `${t.weight} ${px(t.size)}/${px(t.line)} ${role === 'mono' ? 'var(--font-mono)' : 'var(--font-ui)'}`);
  }

  section('Space (4 px grid; the name is the pixel value)');
  for (const s of tokens.space) decl(`space-${s}`, px(s));
  section('Radius');
  for (const [k, v] of Object.entries(tokens.radius)) decl(`radius-${k}`, px(v));
  section('Density');
  for (const [k, v] of Object.entries(tokens.density)) decl(`row-height-${k}`, px(v));
  decl('row-height', `var(--row-height-${tokens.defaultDensity})`);
  section('Layout');
  for (const [k, v] of Object.entries(tokens.layout)) decl(kebab(k), px(v));
  decl('icon-stroke', String(tokens.iconStroke));
  section('Motion');
  decl('duration-fast', `${tokens.motion.fast}ms`);
  decl('duration-base', `${tokens.motion.base}ms`);
  decl('duration-slow', `${tokens.motion.slow}ms`);
  decl('duration-move', `${tokens.motion.base}ms`);
  decl('ease-standard', tokens.motion.easing);
  section('Focus');
  decl('focus-ring-width', px(tokens.focusRing.width));
  decl('focus-ring-offset', px(tokens.focusRing.offset));

  const contrastMore = Object.entries(tokens.colorsContrastMore).map(([key, p]) => {
    assertInGamut(`contrastMore.${key}.light`, p.light);
    assertInGamut(`contrastMore.${key}.dark`, p.dark);
    return `      --${kebab(key)}: ${pair(p)};`;
  });
  /** Sidebar-scoped colour declarations over the macOS vibrancy material (`indent` spaces deep). */
  const vibrancyDecls = (map, label, indent) =>
    Object.entries(map).map(([key, p]) => {
      assertInGamut(`${label}.${key}.light`, p.light);
      assertInGamut(`${label}.${key}.dark`, p.dark);
      return `${' '.repeat(indent)}--${kebab(key)}: ${pair(p)};`;
    });
  const vibrancy = vibrancyDecls(tokens.colorsVibrancySidebar, 'vibrancySidebar', 4);
  const vibrancyMore = vibrancyDecls(tokens.colorsVibrancySidebarContrastMore, 'vibrancySidebarContrastMore', 6);
  const densities = Object.entries(tokens.density)
    .filter(([k]) => k !== tokens.defaultDensity)
    .map(([k]) => `  :root[data-density='${k}'] {\n    --row-height: var(--row-height-${k});\n  }`);

  return [
    `/* ${HEADER} */`,
    '@layer tokens {',
    '  :root {',
    '    color-scheme: light dark;',
    ...lines,
    '  }',
    '',
    "  :root[data-theme='light'] {\n    color-scheme: light;\n  }",
    "  :root[data-theme='dark'] {\n    color-scheme: dark;\n  }",
    ...densities,
    "  :root[data-font='pretendard'] {\n    --font-ui: var(--font-pretendard);\n  }",
    '',
    '  /* Sidebar text over the macOS vibrancy material (tokens.ts colorsVibrancySidebar). */',
    "  :root[data-vibrancy='1'] .sidebar {",
    ...vibrancy,
    '  }',
    '',
    '  @media (prefers-contrast: more) {',
    '    :root {',
    ...contrastMore,
    '    }',
    "    :root[data-vibrancy='1'] .sidebar {",
    ...vibrancyMore,
    '    }',
    '  }',
    '',
    '  /* Reduced motion keeps fades but drops movement. */',
    '  @media (prefers-reduced-motion: reduce) {',
    '    :root {',
    '      --duration-move: 0ms;',
    '    }',
    '  }',
    '}',
    '',
  ].join('\n');
}

export function renderTs() {
  const hex = (theme) => {
    const out = {};
    for (const [key, p] of Object.entries(tokens.colors)) {
      const c = color.parseColor(p[theme]);
      if (c.a === 1) out[key] = color.toHex(c);
    }
    return out;
  };
  const themes = { light: hex('light'), dark: hex('dark') };
  const obj = (o, indent) =>
    Object.entries(o)
      .map(([k, v]) => `${indent}${k}: '${v}',`)
      .join('\n');
  // One less than the toolbar: the overlay must not paint over the toolbar's 1 px bottom hairline (Task 8 critique m3).
  const overlay = (t) =>
    `{ color: '${themes[t].bgWindow}', symbolColor: '${themes[t].textSecondary}', height: ${tokens.layout.toolbarHeight - 1} }`;
  return [
    `// ${HEADER}`,
    '// Opaque theme colours as hex for the main process (no CSS available there).',
    '',
    'export const themeHex = {',
    '  light: {',
    obj(themes.light, '    '),
    '  },',
    '  dark: {',
    obj(themes.dark, '    '),
    '  },',
    '} as const;',
    '',
    '/** BrowserWindow `backgroundColor` per theme, so the first frame is never white in dark mode. */',
    `export const windowBackground = { light: '${themes.light.bgWindow}', dark: '${themes.dark.bgWindow}' } as const;`,
    '',
    '/** `titleBarOverlay` for Windows/Linux (macOS uses traffic lights instead): 51 tall, above the toolbar\'s hairline. */',
    'export const titleBarOverlay = {',
    `  light: ${overlay('light')},`,
    `  dark: ${overlay('dark')},`,
    '} as const;',
    '',
    `export const trafficLightPosition = { x: ${tokens.layout.trafficLightX}, y: ${tokens.layout.trafficLightY} } as const;`,
    '',
  ].join('\n');
}

const outputs = [
  [path.join(designDir, 'tokens.css'), renderCss()],
  [path.join(designDir, 'tokens.generated.ts'), renderTs()],
];

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [file, content] of outputs) {
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current === content) continue;
    if (check) {
      console.error(`stale: ${path.relative(process.cwd(), file)} (run pnpm tokens)`);
      stale++;
    } else {
      writeFileSync(file, content);
      console.log(`wrote ${path.relative(process.cwd(), file)}`);
    }
  }
  if (stale) process.exit(1);
}
