#!/usr/bin/env node
// Builds docs/design/mockups/assets/icons.js: the lucide icons (ISC, pinned
// `lucide-static` devDependency) referenced by the mockup scripts, inlined as SVG
// bodies so the mockups open from file:// without a bundler.
// Every quoted kebab-case string in the mockup JS that names a lucide icon is included.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'docs/design/mockups/assets');
const require = createRequire(import.meta.url);
const pkgDir = path.dirname(require.resolve('lucide-static/package.json'));
const iconDir = path.join(pkgDir, 'icons');
const { version } = JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
const license = readFileSync(path.join(pkgDir, 'LICENSE'), 'utf8').trim();

const sources = readdirSync(assets).filter((f) => f.endsWith('.js') && f !== 'icons.js');
const names = new Set();
for (const file of sources) {
  const text = readFileSync(path.join(assets, file), 'utf8');
  for (const m of text.matchAll(/['"]([a-z][a-z0-9-]*)['"]/g)) {
    if (existsSync(path.join(iconDir, `${m[1]}.svg`))) names.add(m[1]);
  }
}

const entries = [...names].sort().map((name) => {
  const svg = readFileSync(path.join(iconDir, `${name}.svg`), 'utf8');
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  return `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`;
});

const out = `/*
 * Generated by scripts/build-mockup-icons.mjs from lucide-static ${version} — do not edit.
 * ${names.size} icons. Licence of the icons:
 *
${license.split('\n').map((l) => ` * ${l}`.trimEnd()).join('\n')}
 */
window.MockupIcons = {
${entries.join('\n')}
};
`;
writeFileSync(path.join(assets, 'icons.js'), out);
console.log(`icons.js: ${names.size} icons`);
